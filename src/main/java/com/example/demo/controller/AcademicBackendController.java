    @PostMapping("/student/raise-ticket")
    public String saveTicket(
            Authentication auth,
            @RequestParam String subject,
            @RequestParam String category,
            @RequestParam String description,
            RedirectAttributes redirect) {

        requireRole(auth, "STUDENT");

        String email = currentEmail(auth);

        subject = clean(subject);
        category = clean(category).toUpperCase();
        description = clean(description);

        if (subject.isBlank() ||
                description.isBlank() ||
                subject.length() > 150 ||
                description.length() > 1000) {

            redirect.addFlashAttribute(
                    "error",
                    "Invalid subject or description length."
            );

            return "redirect:/student/raise-ticket";
        }

        if (!List.of(
                "ACADEMIC",
                "ATTENDANCE",
                "EXAMINATION",
                "SUBMISSION",
                "TECHNICAL",
                "OTHER"
        ).contains(category)) {

            redirect.addFlashAttribute(
                    "error",
                    "Invalid ticket category."
            );

            return "redirect:/student/raise-ticket";
        }

        db.update("""
            INSERT INTO support_tickets
            (student_email, subject, category, description, status)
            VALUES (?, ?, ?, ?, 'OPEN')
        """, email, subject, category, description);

        redirect.addFlashAttribute(
                "message",
                "Support ticket raised successfully."
        );

        return "redirect:/student/my-tickets";
    }

