    // ================= ROLE VALIDATION =================

    private void requireRole(Authentication auth, String role) {

        if (auth == null ||
                auth.getAuthorities().stream()
                        .noneMatch(authority ->
                                authority.getAuthority().equals("ROLE_" + role))) {

            throw new AccessDeniedException("Access denied");
        }
    }

    private String currentEmail(Authentication auth) {
        return auth.getName();
    }

    // ================= STUDENT EXAMINATION =================

    @GetMapping("/student/examination")
    public String studentGrades(
            Authentication auth,
            Model model) {

        requireRole(auth, "STUDENT");

        model.addAttribute("grades", db.queryForList("""
            SELECT course_code, subject, vertical, am, credits,
                   cia_obt, cia_max,
                   see_obt, see_max,
                   tw_obt, tw_max,
                   pr_obt, pr_max,

                   (cia_obt + see_obt + tw_obt + pr_obt) AS total_obt,

                   CASE
                       WHEN 100.0 * (cia_obt + see_obt + tw_obt + pr_obt)
                            / NULLIF((cia_max + see_max + tw_max + pr_max), 0) >= 90 THEN 'O'
                       WHEN 100.0 * (cia_obt + see_obt + tw_obt + pr_obt)
                            / NULLIF((cia_max + see_max + tw_max + pr_max), 0) >= 80 THEN 'A+'
                       WHEN 100.0 * (cia_obt + see_obt + tw_obt + pr_obt)
                            / NULLIF((cia_max + see_max + tw_max + pr_max), 0) >= 70 THEN 'A'
                       WHEN 100.0 * (cia_obt + see_obt + tw_obt + pr_obt)
                            / NULLIF((cia_max + see_max + tw_max + pr_max), 0) >= 60 THEN 'B+'
                       WHEN 100.0 * (cia_obt + see_obt + tw_obt + pr_obt)
                            / NULLIF((cia_max + see_max + tw_max + pr_max), 0) >= 55 THEN 'B'
                       WHEN 100.0 * (cia_obt + see_obt + tw_obt + pr_obt)
                            / NULLIF((cia_max + see_max + tw_max + pr_max), 0) >= 50 THEN 'C'
                       WHEN 100.0 * (cia_obt + see_obt + tw_obt + pr_obt)
                            / NULLIF((cia_max + see_max + tw_max + pr_max), 0) >= 40 THEN 'P'
                       ELSE 'F'
                   END AS grade

            FROM subject_grades
            WHERE LOWER(student_email) = LOWER(?)
            ORDER BY course_code
        """, currentEmail(auth)));

        return "student/examination";
    }

