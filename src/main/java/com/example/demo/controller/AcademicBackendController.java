    // ================= STUDENT ATTENDANCE =================

    @GetMapping("/student/attendance")
    public String studentAttendance(
            Authentication auth,
            Model model) {

        requireRole(auth, "STUDENT");

        String email = currentEmail(auth);

        List<Map<String, Object>> records = db.queryForList("""
            SELECT subject, attendance_date, present
            FROM attendance_records
            WHERE LOWER(student_email) = LOWER(?)
            ORDER BY attendance_date DESC
        """, email);

        List<Map<String, Object>> summary = db.queryForList("""
            SELECT subject,
                   COUNT(*) AS total_classes,
                   SUM(CASE WHEN present THEN 1 ELSE 0 END) AS attended,
                   ROUND(
                       100.0 * SUM(CASE WHEN present THEN 1 ELSE 0 END) / COUNT(*),
                       2
                   ) AS percentage
            FROM attendance_records
            WHERE LOWER(student_email) = LOWER(?)
            GROUP BY subject
            ORDER BY subject
        """, email);

        model.addAttribute("attendanceRecords", records);
        model.addAttribute("attendanceSummary", summary);

        return "student/attendance";
    }

